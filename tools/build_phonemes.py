"""Expected phonemes for the phonics-api say-it check -> src/data/phonemes.ts PHONEMES {word: [ARPABET]}: every compound of
COMPOUND_PAIRS (src/data/compounds.ts) and both of its parts (the parts are the rivals: "pan" alone must not pass for
"pancake"), from the company phonics-api's own G2P (phonics-kit/tools/papi.py g2p, cached). Re-run after adding a card.
usage: python3 tools/build_phonemes.py      (key: ~/.config/phonics-api/key - never printed)
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(pathlib.Path.home() / 'Documents/Jini/2026/Phonics/phonics-kit/tools'))
import papi  # noqa: E402

src = (ROOT / 'src/data/compounds.ts').read_text()
pairs = re.findall(r"word1:'(\w+)',\s*word2:'(\w+)',\s*result:'(\w+)'", src)
assert len(pairs) >= 30, len(pairs)
words = sorted({w for p in pairs for w in p})
table = papi.g2p(words, log=lambda *a: None)
body = ',\n'.join(f'  {w}: {json.dumps(table[w])}' for w in sorted(table))
(ROOT / 'src/data/phonemes.ts').write_text(
    '// Generated by tools/build_phonemes.py - do not edit. Expected phonemes (phonics-api G2P) of every compound and its parts:\n'
    '// PhonicsAPI.judge compares what the server heard with these (the say-it turn, src/gl/sayJudge.ts).\n'
    f'export const PHONEMES: Record<string, string[]> = {{\n{body},\n}};\n')
print(f'{len(pairs)} compounds, {len(table)} words -> src/data/phonemes.ts')
